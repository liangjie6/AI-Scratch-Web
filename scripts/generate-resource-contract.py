from __future__ import annotations

import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))

from resource_contract import (  # noqa: E402
    RESOURCE_CONTRACT_VERSION,
    RESOURCE_DIAGNOSTIC_CODES,
    RESOURCE_ERROR_CODES,
    RESOURCE_SOURCE_SPECS,
    resource_operation_matrix,
)


operations = resource_operation_matrix()
names = [item['op'] for item in operations]
contract = json.dumps(operations, ensure_ascii=False, indent=2)
sources = json.dumps(list(RESOURCE_SOURCE_SPECS), ensure_ascii=False, indent=2)
errors = json.dumps(list(RESOURCE_ERROR_CODES), ensure_ascii=False, indent=2)
diagnostics = json.dumps(list(RESOURCE_DIAGNOSTIC_CODES), ensure_ascii=False, indent=2)
content = f'''// Generated by scripts/generate-resource-contract.py. Do not edit manually.

export const RESOURCE_CONTRACT_VERSION = {RESOURCE_CONTRACT_VERSION} as const;
export const RESOURCE_OPERATION_NAMES = {json.dumps(names, ensure_ascii=False)} as const;
export type ResourceOperationName = typeof RESOURCE_OPERATION_NAMES[number];
export const RESOURCE_OPERATION_CONTRACT = {contract} as const;
export type ResourceOperationSpec = typeof RESOURCE_OPERATION_CONTRACT[number];
export const RESOURCE_SOURCE_CONTRACT = {sources} as const;
export type ResourceSourceSpec = typeof RESOURCE_SOURCE_CONTRACT[number];
export const RESOURCE_DIAGNOSTIC_CODES = {diagnostics} as const;
export const RESOURCE_ERROR_CODES = {errors} as const;
'''
output = ROOT / 'frontend' / 'src' / 'ai-blocks' / 'generated' / 'resource-contract.ts'
if '--check' in sys.argv:
    if not output.exists() or output.read_text(encoding='utf-8') != content:
        raise SystemExit(f'generated resource contract is stale: {output}')
    print(f'fresh: {output}')
else:
    output.write_text(content, encoding='utf-8', newline='\n')
    print(output)
